import React, { useState, useRef, useEffect } from 'react';
import { ShieldCheck, KeyRound, Lock, AlertTriangle, ArrowRight } from 'lucide-react';
import { api } from '../../services/api';
import { useToast } from './Toast';

interface PinModalProps {
  isOpen: boolean;
  onSuccess: () => void;
  onClose?: () => void;
}

export const PinModal: React.FC<PinModalProps> = ({ isOpen, onSuccess, onClose }) => {
  const [pinDigits, setPinDigits] = useState<string[]>(['', '', '', '', '', '']);
  const [isLoading, setIsLoading] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [isShaking, setIsShaking] = useState(false);
  const [retryAfter, setRetryAfter] = useState<number | null>(null);
  const inputRefs = useRef<(HTMLInputElement | null)[]>([]);
  const { toast } = useToast();

  useEffect(() => {
    if (isOpen) {
      setTimeout(() => {
        inputRefs.current[0]?.focus();
      }, 100);
    }
  }, [isOpen]);

  useEffect(() => {
    let timer: any;
    if (retryAfter && retryAfter > 0) {
      timer = setInterval(() => {
        setRetryAfter(prev => (prev && prev > 1 ? prev - 1 : null));
      }, 1000);
    }
    return () => clearInterval(timer);
  }, [retryAfter]);

  if (!isOpen) return null;

  const handleDigitChange = (index: number, val: string) => {
    const char = val.replace(/\D/g, '').slice(-1);
    const newDigits = [...pinDigits];
    newDigits[index] = char;
    setPinDigits(newDigits);
    setErrorMsg(null);

    if (char && index < 5) {
      inputRefs.current[index + 1]?.focus();
    }

    // Auto submit if all 6 digits filled
    if (newDigits.every(d => d !== '') && index === 5) {
      submitPin(newDigits.join(''));
    }
  };

  const handleKeyDown = (index: number, e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === 'Backspace' && !pinDigits[index] && index > 0) {
      inputRefs.current[index - 1]?.focus();
    } else if (e.key === 'ArrowLeft' && index > 0) {
      inputRefs.current[index - 1]?.focus();
    } else if (e.key === 'ArrowRight' && index < 5) {
      inputRefs.current[index + 1]?.focus();
    } else if (e.key === 'Enter') {
      submitPin(pinDigits.join(''));
    }
  };

  const handlePaste = (e: React.ClipboardEvent) => {
    e.preventDefault();
    const pasted = e.clipboardData.getData('text').trim().replace(/\D/g, '').slice(0, 6);
    if (!pasted) return;
    const newDigits = ['', '', '', '', '', ''];
    for (let i = 0; i < pasted.length; i++) {
      newDigits[i] = pasted[i];
    }
    setPinDigits(newDigits);
    if (pasted.length === 6) {
      submitPin(pasted);
    } else {
      inputRefs.current[pasted.length]?.focus();
    }
  };

  const submitPin = async (fullPin: string) => {
    if (fullPin.length !== 6 || isLoading || (retryAfter && retryAfter > 0)) return;
    setIsLoading(true);
    setErrorMsg(null);

    const result = await api.verifyPin(fullPin);
    setIsLoading(false);

    if (result.ok) {
      toast('PIN verified. Access granted to Antigravity Studio', 'success');
      onSuccess();
    } else {
      setIsShaking(true);
      setErrorMsg(result.error || 'Invalid 6-digit PIN');
      setTimeout(() => setIsShaking(false), 500);
      setPinDigits(['', '', '', '', '', '']);
      inputRefs.current[0]?.focus();
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-xl animate-fade-in">
      <div
        className={`w-full max-w-md bg-studio-panel/95 border border-studio-border rounded-2xl p-6 sm:p-8 shadow-2xl relative overflow-hidden ${
          isShaking ? 'animate-shake' : ''
        }`}
      >
        {/* Ambient Top Glow */}
        <div className="absolute top-0 left-1/2 -translate-x-1/2 w-48 h-24 bg-gradient-to-b from-indigo-500/20 to-transparent blur-2xl pointer-events-none" />

        <div className="flex flex-col items-center text-center mb-6">
          <div className="w-14 h-14 rounded-2xl bg-indigo-500/10 border border-indigo-500/30 flex items-center justify-center mb-4 text-indigo-400 shadow-glow-indigo">
            <Lock className="w-7 h-7" />
          </div>
          <h2 className="text-xl font-bold tracking-tight text-white flex items-center gap-2">
            Antigravity Security Lock
          </h2>
          <p className="text-xs sm:text-sm text-studio-muted mt-1 max-w-xs">
            Enter the 6-digit security PIN generated by your Antigravity backend.
          </p>
        </div>

        {/* 6 Digit Inputs */}
        <div className="flex justify-center items-center gap-2 sm:gap-3 my-6" onPaste={handlePaste}>
          {pinDigits.map((digit, idx) => (
            <input
              key={idx}
              ref={el => (inputRefs.current[idx] = el)}
              type="password"
              inputMode="numeric"
              pattern="[0-9]*"
              maxLength={1}
              value={digit}
              disabled={isLoading || (retryAfter !== null && retryAfter > 0)}
              onChange={e => handleDigitChange(idx, e.target.value)}
              onKeyDown={e => handleKeyDown(idx, e)}
              className={`w-11 h-13 sm:w-12 sm:h-14 text-center text-xl font-bold rounded-xl border bg-studio-card/80 text-white outline-none transition-all duration-150 focus:border-indigo-500 focus:ring-2 focus:ring-indigo-500/30 ${
                digit ? 'border-indigo-500/70 shadow-glow-indigo' : 'border-studio-border'
              }`}
            />
          ))}
        </div>

        {/* Error or Rate Limit notice */}
        {errorMsg && (
          <div className="flex items-center gap-2 text-rose-400 text-xs sm:text-sm bg-rose-950/40 border border-rose-800/40 rounded-xl p-3 mb-5 justify-center">
            <AlertTriangle className="w-4 h-4 shrink-0" />
            <span>{errorMsg}</span>
          </div>
        )}

        {retryAfter !== null && retryAfter > 0 && (
          <div className="text-amber-400 text-xs sm:text-sm bg-amber-950/40 border border-amber-800/40 rounded-xl p-3 mb-5 text-center">
            Rate limited. Please retry in {retryAfter}s.
          </div>
        )}

        <div className="flex flex-col gap-3">
          <button
            onClick={() => submitPin(pinDigits.join(''))}
            disabled={pinDigits.some(d => d === '') || isLoading || (retryAfter !== null && retryAfter > 0)}
            className="w-full flex items-center justify-center gap-2 py-3 px-4 rounded-xl bg-gradient-to-r from-indigo-600 to-indigo-500 hover:from-indigo-500 hover:to-indigo-400 text-white font-medium text-sm transition-all duration-200 shadow-glow-indigo disabled:opacity-40 disabled:cursor-not-allowed cursor-pointer"
          >
            {isLoading ? (
              <span className="flex items-center gap-2">
                <span className="w-4 h-4 border-2 border-white/20 border-t-white rounded-full animate-spin" />
                Verifying Credentials...
              </span>
            ) : (
              <>
                <span>Unlock AI Studio</span>
                <ArrowRight className="w-4 h-4" />
              </>
            )}
          </button>

          {onClose && (
            <button
              onClick={onClose}
              className="text-xs text-studio-subtle hover:text-studio-muted py-1 transition-colors"
            >
              Continue in Guest View
            </button>
          )}
        </div>

        <div className="mt-6 pt-4 border-t border-studio-border/60 flex items-center justify-between text-[11px] text-studio-subtle">
          <span className="flex items-center gap-1">
            <KeyRound className="w-3.5 h-3.5 text-indigo-400" />
            Stored in local browser
          </span>
          <span>Port 51125 Protected</span>
        </div>
      </div>
    </div>
  );
};
